// The secret key on a server: raw SQL through the connection pooler
// (parameters, types, multi-statement transactions, rollback), migrations,
// row-level security bypass — and its refusal everywhere else. Then types
// round-tripped through the Data API.
import {check, refused, assert} from '../lib.mjs';

export default async function server(ctx) {
  const {server, alice, posts: {p1, p2, p5}} = ctx;

  await check('sql: tagged template with parameters', async () => {
    const rows = await server.sql`SELECT id, title FROM posts WHERE likes >= ${10} AND status = ${'published'} ORDER BY id`;
    assert.ok(rows.length >= 2);
    assert.ok(rows.every((r) => typeof r.title === 'string'));
  });

  await check('sql: raw with $1 parameters and exec row counts', async () => {
    const [row] = await server.raw('SELECT $1::int + $2::int AS total, $3::text AS label', [40, 2, `it's`]);
    assert.deepEqual(row, {total: 42, label: `it's`});
    const result = await server.exec('UPDATE products SET stock = stock WHERE region = $1', ['IN']);
    assert.equal(result.command?.toLowerCase(), 'update');
    assert.ok(result.rowCount >= 2);
  });

  await check('sql: the secret key bypasses row-level security (every draft is visible)', async () => {
    const rows = await server.from('posts').select('id').in('id', [p2.id, p5.id]).order('id');
    assert.deepEqual(rows.map((r) => r.id), [p2.id, p5.id]);
  });

  await check('sql: types round-trip with parameters (numeric, bigint, jsonb, arrays, uuid, timestamptz, date, enum)', async () => {
    const [row] = await server.raw(
      `SELECT $1::numeric(20,6)::text AS amount, $2::bigint::text AS big, $3::jsonb AS doc, $4::text[] AS words, $5::int[] AS nums,
              $6::uuid AS id, $7::timestamptz AS at, $8::date AS day, $9::post_status AS status, $10::boolean AS flag`,
      ['12345678901234.123456', '9007199254740993', {a: [1, {b: null}], 'é': 'ü'}, ['a', 'b,c', 'd"e'], [1, 2, 3],
        alice.id, '2026-10-28T10:00:00+05:30', '2026-10-28', 'archived', true]
    );
    assert.equal(row.amount, '12345678901234.123456');
    assert.equal(row.big, '9007199254740993');
    assert.deepEqual(row.doc, {a: [1, {b: null}], 'é': 'ü'});
    assert.deepEqual(row.words, ['a', 'b,c', 'd"e']);
    assert.deepEqual(row.nums, [1, 2, 3]);
    assert.equal(row.id, alice.id);
    assert.equal(new Date(row.at).toISOString(), '2026-10-28T04:30:00.000Z');
    assert.equal(String(row.day).slice(0, 10), '2026-10-28');
    assert.equal(row.status, 'archived');
    assert.equal(row.flag, true);
  });

  await check('sql: several statements in one transaction commit together', async () => {
    const results = await server.sqlTransaction([
      'CREATE TABLE audit_log (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, what text NOT NULL)',
      {sql: 'INSERT INTO audit_log (what) VALUES ($1), ($2)', params: ['one', 'two']},
      'SELECT count(*)::int AS n FROM audit_log'
    ]);
    assert.equal(results.length, 3);
    assert.equal(results[2].rows[0].n, 2);
  });

  await check('sql: a failing statement rolls the whole transaction back', async () => {
    const e = await refused(server.sqlTransaction([
      {sql: 'INSERT INTO audit_log (what) VALUES ($1)', params: ['three']},
      {sql: 'INSERT INTO audit_log (what) VALUES (NULL)', params: []}
    ]), {sqlstate: '23502'});
    assert.ok(e.status >= 400);
    const [{n}] = await server.raw('SELECT count(*)::int AS n FROM audit_log');
    assert.equal(n, 2);
  });

  await check('sql: the connection pooler keeps no session state between calls (SET does not leak)', async () => {
    await server.exec(`SET application_name = 'leak-test'`);
    const [row] = await server.raw(`SELECT current_setting('application_name') AS name`);
    assert.notEqual(row.name, 'leak-test');
  });

  await check('migrations: versioned migrate and rollback, migrator inspection', async () => {
    const migrations = [
      {id: '2026_10_28_01_bookmarks', up: 'CREATE TABLE bookmarks (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, url text NOT NULL)', down: 'DROP TABLE bookmarks'},
      {id: '2026_10_28_02_title', up: (m) => m.addColumn('bookmarks', 'title', 'text').createIndex('bookmarks', 'url', {unique: true}), down: (m) => m.dropColumn('bookmarks', 'title')}
    ];
    assert.deepEqual(await server.migrate(migrations), ['2026_10_28_01_bookmarks', '2026_10_28_02_title']);
    assert.deepEqual(await server.migrate(migrations), []);
    assert.equal(await server.migrator.hasColumn('bookmarks', 'title'), true);
    assert.deepEqual(await server.rollback(migrations, {steps: 1}), ['2026_10_28_02_title']);
    assert.equal(await server.migrator.hasColumn('bookmarks', 'title'), false);
    assert.ok((await server.migrator.tables()).includes('bookmarks'));
  });

  await check('sql: refused for the publishable key (403 secret_key_required)', async () => {
    await refused(ctx.anon.raw('SELECT 1'), {status: 403, code: 'secret_key_required'});
  });

  await check('sql: refused for a signed-in user', async () => {
    await refused(alice.db.sql`SELECT * FROM posts`, {status: 403, code: 'secret_key_required'});
  });

  // ── types through the Data API ───────────────────────────────────────────
  await check('types: numeric keeps every digit as text (::text)', async () => {
    const created = await alice.db.from('posts').create({title: 'Numeric', price: '1234567890.1234', big: '9007199254740993'});
    const [row] = await alice.db.from('posts').select('price::text, big::text').eq('id', created.id);
    assert.deepEqual(row, {price: '1234567890.1234', big: '9007199254740993'});
    ctx.numericPost = created;
  });

  await check('types: timestamptz from any time zone is one instant; date stays a date', async () => {
    const post = await alice.db.from('posts').create({title: 'Zones', created_at: '2026-10-28T10:00:00+05:30', published_on: '2026-10-28'});
    const [row] = await alice.db.from('posts').select('created_at, published_on').eq('id', post.id);
    assert.equal(new Date(row.created_at).toISOString(), '2026-10-28T04:30:00.000Z');
    assert.equal(row.published_on, '2026-10-28');
    const same = await alice.db.from('posts').eq('created_at', '2026-10-27T23:00:00-05:30');
    assert.deepEqual(same.map((r) => r.id), [post.id]);
    const byDate = await alice.db.from('posts').eq('created_at', new Date('2026-10-28T04:30:00Z'));
    assert.deepEqual(byDate.map((r) => r.id), [post.id]);
  });

  await check('types: jsonb, text[], int[], enum, uuid and double round-trip', async () => {
    const meta = {nested: {list: [1, 'two', {three: 3}], empty: {}, nil: null}, unicode: 'नमस्ते'};
    const post = await alice.db.from('posts').create({title: 'Types', meta, labels: ['a b', 'c,d', 'e"f', 'g\\h'], scores: [-1, 0, 2147483647], status: 'archived', editor_id: ctx.bob.id, rating: 0.1 + 0.2});
    const [row] = await alice.db.from('posts').select('meta, labels, scores, status, editor_id, rating').eq('id', post.id);
    assert.deepEqual(row.meta, meta);
    assert.deepEqual(row.labels, ['a b', 'c,d', 'e"f', 'g\\h']);
    assert.deepEqual(row.scores, [-1, 0, 2147483647]);
    assert.equal(row.status, 'archived');
    assert.equal(row.editor_id, ctx.bob.id);
    assert.equal(row.rating, 0.1 + 0.2);
    assert.deepEqual((await alice.db.from('posts').contains('labels', ['c,d'])).map((r) => r.id), [post.id]);
  });
}
