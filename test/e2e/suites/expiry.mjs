// Short-lived access tokens (a second project with access_token_ttl 6 s):
// requests refresh by themselves, an expired token is refused (never
// treated as anon), and realtime keeps delivering across expiry.
import {check, refused, assert, newProject, hasControl, note, redact, sleep, until, email, PASSWORD} from '../lib.mjs';

const TTL = 6;

export default async function expiry(ctx) {
  let project;
  if (process.env.TTL_API_URL) {
    project = {api_url: process.env.TTL_API_URL, publishable_key: process.env.TTL_PUBLISHABLE_KEY, secret_key: process.env.TTL_SECRET_KEY};
  } else if (await hasControl()) {
    project = await newProject({access_token_ttl: TTL});
  } else {
    note('no TTL_API_URL and no harness control endpoint: the token-expiry checks (a project with a 6 s token) are skipped');
    return;
  }
  redact(project.publishable_key, project.secret_key);
  const make = (key, options = {}) => ctx.sdk.createClient(project.api_url, key, {persistSession: false, ...options});
  const server = make(project.secret_key);
  await server.sqlTransaction([
    `CREATE TABLE IF NOT EXISTS notes (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id uuid NOT NULL DEFAULT auth.uid(), body text NOT NULL)`,
    `ALTER TABLE notes ENABLE ROW LEVEL SECURITY`,
    `DROP POLICY IF EXISTS own ON notes`,
    `CREATE POLICY own ON notes FOR ALL TO authenticated USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid())`,
    `GRANT SELECT, INSERT, UPDATE, DELETE ON notes TO authenticated`,
    `GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO authenticated`,
    `CREATE OR REPLACE TRIGGER plexivo_realtime AFTER INSERT OR UPDATE OR DELETE ON notes FOR EACH ROW EXECUTE FUNCTION auth.realtime_notify('id')`
  ]);

  const db = make(project.publishable_key);
  const events = [];
  db.auth.onAuthStateChange((e, s) => { events.push(e); if (s) redact(s.access_token, s.refresh_token); });
  const address = email('expiry');
  const first = await db.auth.signUp({email: address, password: PASSWORD});
  redact(first.access_token, first.refresh_token);
  await db.from('notes').create({body: 'before expiry'});

  await check('expiry: the session lasts the project\'s access_token_ttl', async () => {
    assert.equal(first.expires_in, TTL);
  });

  // Realtime across expiry, started now so it lives through it.
  const got = [];
  const statuses = [];
  const ch = db.channel('changes:notes').onChange((c) => got.push(c)).subscribe((s) => statuses.push(s));
  await ch.ready();

  // A second client whose first refresh fails (a flaky network), so the
  // server ends its channel at expiry and the SDK must rejoin after it.
  let blockRefresh = true;
  const flaky = make(project.publishable_key, {
    fetch: (url, init) => (blockRefresh && String(url).endsWith('/auth/refresh') ? Promise.reject(new TypeError('network down')) : fetch(url, init))
  });
  flaky.auth.onAuthStateChange((_e, s) => s && redact(s.access_token, s.refresh_token));
  await flaky.auth.signInWithPassword({email: address, password: PASSWORD});
  const flakyGot = [];
  const flakyStatuses = [];
  const flakyErrors = [];
  const fch = flaky.channel('changes:notes').onChange((c) => flakyGot.push(c)).onError((e) => flakyErrors.push(e.code)).subscribe((s) => flakyStatuses.push(s));
  await fch.ready();

  await sleep((TTL + 2) * 1000);

  await check('expiry: an expired token is refused with 401 token_expired, never served as anon', async () => {
    const stale = make(project.publishable_key, {initialSession: {...first, refresh_token: undefined}});
    await refused(stale.from('notes').select('*'), {status: 401, code: 'token_expired'});
    await refused(stale.auth.getUser(), {status: 401});
  });

  await check('expiry: a request after expiry refreshes the session by itself and succeeds', async () => {
    const rows = await db.from('notes').select('body');
    assert.ok(rows.some((r) => r.body === 'before expiry'));
    assert.ok(events.includes('TOKEN_REFRESHED'));
    assert.notEqual(db.auth.getSession().access_token, first.access_token);
  });

  await check('expiry: realtime moves to the fresh token and keeps delivering', async () => {
    const note = await db.from('notes').create({body: 'after expiry'});
    await until(() => got.some((c) => c.record?.id === note.id), {timeout: 15_000, what: 'the change after expiry'});
    assert.ok(statuses.filter((s) => s === 'SUBSCRIBED').length >= 2, statuses.join(','));
  });

  await check('expiry: when the server ends the channel at expiry, the SDK refreshes and rejoins', async () => {
    blockRefresh = false;
    // The first change after expiry ends the stale channel; the SDK rejoins with a fresh token.
    await db.from('notes').create({body: 'wakes the stale channel'});
    await until(() => flakyStatuses.filter((s) => s === 'SUBSCRIBED').length >= 2, {timeout: 20_000, what: `the rejoin (statuses ${flakyStatuses.join(',')}; errors ${flakyErrors.join(',')}; state ${fch.state})`});
    const later = await db.from('notes').create({body: 'after the rejoin'});
    await until(() => flakyGot.some((c) => c.record?.id === later.id), {timeout: 15_000, what: 'the change after the rejoin'});
    assert.ok(flakyStatuses.includes('RECONNECTING'));
  });

  ch.unsubscribe();
  fch.unsubscribe();

  await check('expiry: a revoked refresh token cannot bring a session back', async () => {
    const other = make(project.publishable_key);
    await other.auth.signInWithPassword({email: address, password: PASSWORD});
    const refresh = other.auth.getSession().refresh_token;
    await other.auth.signOut();
    await refused(make(project.publishable_key).auth.refreshSession(refresh), {status: 401, code: 'invalid_refresh_token'});
  });
}
