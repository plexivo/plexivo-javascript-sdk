const scalar = {
  string: 'string',
  number: 'number',
  boolean: 'boolean',
  json: 'Json'
};

function fieldType(field) {
  const base = scalar[field.type];
  if (!base) throw new Error(`Unsupported schema type: ${field.type}`);
  return field.nullable ? `${base} | null` : base;
}

function objectType(fields, optional) {
  if (!Array.isArray(fields)) throw new Error('Invalid schema field list');
  const lines = fields.map((field) => {
    if (!field?.name || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(field.name)) {
      throw new Error('Invalid schema field name');
    }
    return `        ${field.name}${optional || field.nullable ? '?' : ''}: ${fieldType(field)};`;
  });
  return ['{', ...lines, '      }'].join('\n');
}

export function renderTypes(contract) {
  if (contract?.schema !== 'public' || !contract.tables || typeof contract.tables !== 'object') {
    throw new Error('Unsupported Client Data schema contract');
  }

  const tables = Object.entries(contract.tables).sort(([a], [b]) => a.localeCompare(b));
  if (tables.length === 0) throw new Error('Schema contract has no tables');

  const rendered = tables.map(([name, definition]) => {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error('Invalid table name');
    return [
      `    ${name}: {`,
      `      Row: ${objectType(definition.row, false)};`,
      `      Insert: ${objectType(definition.insert, false)};`,
      `      Update: ${objectType(definition.update, true)};`,
      '    };'
    ].join('\n');
  }).join('\n');

  return `// Generated by @plexivo/client from Client Data schema ${contract.version || 'unknown'}.\n` +
    `// Do not include a server key or database credential in frontend code.\n` +
    `export type Json = null | boolean | number | string | Json[] | { [key: string]: Json };\n\n` +
    `export interface Database {\n  public: {\n    Tables: {\n${rendered}\n    };\n  };\n}\n`;
}

// ── types from the live Data API (GET /meta/api) ─────────────────────────

const pgScalar = (type) => {
  const t = String(type || '').toLowerCase();
  if (t.endsWith('[]')) return `${pgScalar(t.slice(0, -2))}[]`;
  if (/^(smallint|integer|bigint|int2|int4|int8|real|double precision|float4|float8|numeric|decimal|serial|bigserial|oid|money)/.test(t)) return 'number';
  if (t === 'boolean' || t === 'bool') return 'boolean';
  if (t === 'json' || t === 'jsonb') return 'Json';
  if (t === 'void') return 'undefined';
  return 'string';
};

const safeName = (name) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : JSON.stringify(name));

/**
 * TypeScript for a project's live Data API: every exposed table's Row,
 * Insert and Update, and every exposed function's Args and Returns.
 *
 *   const api = await db.getApi();
 *   fs.writeFileSync('database.ts', renderApiTypes(api));
 *   const db = createClient<Database>(url, key);
 */
export function renderApiTypes(api) {
  if (!api || !Array.isArray(api.tables)) throw new Error('renderApiTypes takes the result of getApi()');
  const tables = [...api.tables].sort((a, b) => a.name.localeCompare(b.name)).map((t) => {
    const cols = t.columns || [];
    const row = cols.map((c) => `        ${safeName(c.name)}: ${pgScalar(c.type)}${c.not_null ? '' : ' | null'};`);
    const writable = cols.filter((c) => !c.read_only);
    const insert = writable.map((c) => `        ${safeName(c.name)}${c.not_null && !c.has_default ? '' : '?'}: ${pgScalar(c.type)}${c.not_null ? '' : ' | null'};`);
    const update = writable.map((c) => `        ${safeName(c.name)}?: ${pgScalar(c.type)}${c.not_null ? '' : ' | null'};`);
    return [
      `    ${safeName(t.name)}: {`,
      `      Row: {\n${row.join('\n')}\n      };`,
      `      Insert: {\n${insert.join('\n')}\n      };`,
      `      Update: {\n${update.join('\n')}\n      };`,
      '    };'
    ].join('\n');
  });
  const functions = [...(api.functions || [])].sort((a, b) => a.name.localeCompare(b.name)).map((f) => {
    const required = new Set(f.required || []);
    const args = (f.args || []).map((a) => `${safeName(a.name)}${required.has(a.name) ? '' : '?'}: ${pgScalar(a.type)}`);
    const returns = pgScalar(f.returns) + (f.returns_set ? '[]' : '');
    return `    ${safeName(f.name)}: { Args: { ${args.join('; ')} }; Returns: ${returns} };`;
  });
  return '// Generated by @plexivo/client from the live Data API (getApi).\n' +
    '// Do not include a server key or database credential in frontend code.\n' +
    'export type Json = null | boolean | number | string | Json[] | { [key: string]: Json };\n\n' +
    `export interface Database {\n  public: {\n    Tables: {\n${tables.join('\n')}\n    };\n    Functions: {\n${functions.join('\n')}\n    };\n  };\n}\n`;
}
