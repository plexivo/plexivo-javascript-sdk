// @plexivo/client in a real browser: the SDK bundled with esbuild, served
// on an allowed origin, driven in headless Chrome with playwright-core.
//
//   node test/browser/run.mjs
//   PLEXIVO_SDK_ENTRY=/path/to/node_modules/@plexivo/client node test/browser/run.mjs
//
// With API_URL and ALLOWED_ORIGIN (http://127.0.0.1:<port> or
// http://localhost:<port>) the page is served on exactly that origin;
// otherwise a fresh project is created whose allowed origin is the page's.
// A second server on another port is a different origin, which the project
// does not allow.

import {createServer} from 'node:http';
import {readFileSync, statSync} from 'node:fs';
import {join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
import {chromium} from 'playwright-core';
import {check, assert, finish, note, redact, newProject, waitForApi, POOLED} from '../e2e/lib.mjs';

const here = fileURLToPath(new URL('.', import.meta.url));

function sdkEntry() {
  const entry = process.env.PLEXIVO_SDK_ENTRY;
  if (!entry) return resolve(here, '../../src/index.js');
  let file = resolve(entry);
  if (statSync(file).isDirectory()) {
    const pkg = JSON.parse(readFileSync(join(file, 'package.json'), 'utf8'));
    file = join(file, pkg.exports?.['.']?.import || pkg.main);
  }
  return file;
}

async function freePort() {
  const s = createServer();
  await new Promise((r) => s.listen(0, '127.0.0.1', r));
  const {port} = s.address();
  await new Promise((r) => s.close(r));
  return port;
}

// The project, and the origin the page must be served on.
let project;
let origin;
const allowed = process.env.ALLOWED_ORIGIN || '';
const match = allowed.match(/^http:\/\/(127\.0\.0\.1|localhost):(\d+)$/);
if (process.env.API_URL && match) {
  origin = allowed;
  project = {api_url: process.env.API_URL, publishable_key: process.env.PUBLISHABLE_KEY, secret_key: process.env.SECRET_KEY};
} else {
  if (process.env.API_URL) note(`ALLOWED_ORIGIN ${allowed || '(unset)'} is not a local http origin: creating a project for this page's origin`);
  origin = `http://127.0.0.1:${await freePort()}`;
  project = await newProject({origins: [origin]});
}
redact(project.publishable_key, project.secret_key);
const entry = sdkEntry();
console.log(`browser suite: SDK ${entry}`);
console.log(`page origin ${origin}; project ${project.api_url}${POOLED ? ' (pooled)' : ''}`);
await waitForApi(project.api_url);

// The schema, from the server with the secret key.
const {createClient} = await import(new URL(`file://${entry}`).href);
const server = createClient(project.api_url, project.secret_key, {persistSession: false});
await server.sqlTransaction([
  `CREATE TABLE profiles (id uuid PRIMARY KEY DEFAULT auth.uid(), username text NOT NULL UNIQUE)`,
  `ALTER TABLE profiles ENABLE ROW LEVEL SECURITY`,
  `CREATE POLICY profiles_read ON profiles FOR SELECT TO anon, authenticated USING (true)`,
  `CREATE POLICY profiles_own ON profiles FOR INSERT TO authenticated WITH CHECK (id = auth.uid())`,
  `CREATE TABLE notes (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles (id), body text NOT NULL, created_at timestamptz NOT NULL DEFAULT now())`,
  `ALTER TABLE notes ENABLE ROW LEVEL SECURITY`,
  `CREATE POLICY notes_own ON notes FOR ALL TO authenticated USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid())`,
  `GRANT SELECT ON profiles TO anon`,
  `GRANT SELECT, INSERT ON profiles TO authenticated`,
  `GRANT SELECT, INSERT, UPDATE, DELETE ON notes TO authenticated`,
  `GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO authenticated`,
  `CREATE TRIGGER plexivo_realtime AFTER INSERT OR UPDATE OR DELETE ON notes FOR EACH ROW EXECUTE FUNCTION auth.realtime_notify('id')`
]);

// The SDK as a browser bundle: window.Plexivo.
const bundle = await build({
  stdin: {contents: `export * from ${JSON.stringify(entry)};`, resolveDir: here, loader: 'js'},
  bundle: true, format: 'iife', globalName: 'Plexivo', platform: 'browser', target: 'es2022', write: false
});
const sdkJs = bundle.outputFiles[0].text;
const page = (title) => `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${title}</title></head>
<body><h1>${title}</h1><script src="/sdk.js"></script></body></html>`;

function serve(port, title) {
  const s = createServer((req, res) => {
    if (req.url.startsWith('/sdk.js')) {
      res.writeHead(200, {'content-type': 'text/javascript'});
      return res.end(sdkJs);
    }
    res.writeHead(200, {'content-type': 'text/html; charset=utf-8'});
    res.end(page(title));
  });
  return new Promise((r) => s.listen(port, '127.0.0.1', () => r(s)));
}

const port = Number(new URL(origin).port);
const http = await serve(port, 'Plexivo browser test');
const otherPort = await freePort();
const otherHttp = await serve(otherPort, 'Another origin');
const pageUrl = `${origin}/`;

const launch = async () => {
  try {
    return await chromium.launch({headless: true});
  } catch (error) {
    note(`bundled Chromium unavailable (${error.message.split('\n')[0]}); using the installed Google Chrome`);
    return chromium.launch({headless: true, channel: 'chrome'});
  }
};
const browser = await launch();
const cfg = {url: project.api_url, key: project.publishable_key};

try {
  const context = await browser.newContext();
  const tab = await context.newPage();
  const consoleErrors = [];
  tab.on('pageerror', (e) => consoleErrors.push(e.message));
  await tab.goto(pageUrl);

  await check('browser: the page loads the SDK bundle', async () => {
    const version = await tab.evaluate(() => window.Plexivo.VERSION);
    assert.match(String(version), /^\d+\.\d+\.\d+/);
    assert.equal(await tab.evaluate(() => location.origin), origin);
  });

  await check('browser: createClient refuses the secret key in a browser', async () => {
    const out = await tab.evaluate(({url}) => {
      try {
        window.Plexivo.createClient(url, 'plx_secret_' + 'x'.repeat(40));
        return {threw: false};
      } catch (e) {
        return {threw: true, code: e.code, name: e.name};
      }
    }, cfg);
    assert.deepEqual(out, {threw: true, code: 'secret_key_in_browser', name: 'PlexivoError'});
  });

  await check('browser: the server refuses the secret key sent from a page (403 secret_key_in_browser)', async () => {
    const out = await tab.evaluate(async ({url, secret}) => {
      const r = await fetch(`${url}/query/v1`, {method: 'POST', headers: {apikey: secret, 'content-type': 'application/json'}, body: JSON.stringify({op: 'select', from: 'notes'})});
      let body = null;
      try { body = await r.json(); } catch { /* opaque */ }
      return {status: r.status, code: body?.error?.code};
    }, {...cfg, secret: project.secret_key}).catch((e) => ({blocked: e.message}));
    if (out.blocked) assert.fail(`the browser could not read the refusal: ${out.blocked}`);
    assert.deepEqual(out, {status: 403, code: 'secret_key_in_browser'});
  });

  const email = `browser.${Date.now().toString(36)}@example.com`;
  const password = 'correct-Horse-battery-9';

  await check('browser: sign-up keeps the session in localStorage', async () => {
    const out = await tab.evaluate(async ({url, key, email, password}) => {
      const db = window.Plexivo.createClient(url, key);
      const s = await db.auth.signUp({email, password, data: {from: 'browser'}});
      await db.from('profiles').create({username: 'browser-user'});
      const stored = Object.keys(localStorage).filter((k) => k.startsWith('plexivo-client:'));
      return {id: s.user.id, stored: stored.length, meta: s.user.user_metadata};
    }, {...cfg, email, password});
    assert.equal(out.stored, 1);
    assert.deepEqual(out.meta, {from: 'browser'});
  });

  await tab.reload();

  await check('browser: after a reload the session is restored from localStorage', async () => {
    const out = await tab.evaluate(async ({url, key}) => {
      const db = window.Plexivo.createClient(url, key);
      const s = db.auth.getSession();
      const user = await db.auth.getUser();
      return {has: Boolean(s?.access_token), email: user.email};
    }, cfg);
    assert.equal(out.has, true);
    assert.equal(out.email, email);
  });

  await check('browser: CRUD under row-level security, with CORS', async () => {
    const out = await tab.evaluate(async ({url, key}) => {
      const db = window.Plexivo.createClient(url, key);
      const a = await db.from('notes').create({body: 'from the browser'});
      const read = await db.from('notes').eq('id', a.id);
      const [updated] = await db.from('notes').where('id', a.id).update({body: 'edited in the browser'});
      const b = await db.from('notes').create({body: 'to delete'});
      await db.from('notes').delete(b.id);
      const count = await db.from('notes').count();
      return {read: read.length, updated: updated.body, count, trace: db.lastTraceId};
    }, cfg);
    assert.deepEqual({read: out.read, updated: out.updated, count: out.count}, {read: 1, updated: 'edited in the browser', count: 1});
  });

  await check('browser: an embed (many-to-one) in Supabase and GORM styles', async () => {
    const out = await tab.evaluate(async ({url, key}) => {
      const db = window.Plexivo.createClient(url, key);
      const [row] = await db.from('notes').select('body, author:profiles(username)').limit(1);
      const viaPreload = await db.from('notes').preload('profiles').first();
      return {row, preload: viaPreload.profiles.username};
    }, cfg);
    assert.deepEqual(out.row, {body: 'edited in the browser', author: {username: 'browser-user'}});
    assert.equal(out.preload, 'browser-user');
  });

  await check('browser: another user in another browser profile sees none of these rows', async () => {
    const other = await browser.newContext();
    const t2 = await other.newPage();
    await t2.goto(pageUrl);
    const out = await t2.evaluate(async ({url, key}) => {
      const db = window.Plexivo.createClient(url, key);
      await db.auth.signUp({email: `other.${Date.now().toString(36)}@example.com`, password: 'correct-Horse-battery-9'});
      const rows = await db.from('notes').select('*');
      const {data, error} = await window.Plexivo.createClient(url, key, {throwOnError: false, persistSession: false}).from('notes').select('*');
      return {rows: rows.length, anonError: error?.code ?? null, anonData: data};
    }, cfg);
    await other.close();
    assert.equal(out.rows, 0);
    assert.equal(out.anonError, 'permission_denied');
    assert.equal(out.anonData, null);
  });

  await check('browser: realtime delivers an insert over the browser WebSocket', async () => {
    const out = await tab.evaluate(async ({url, key}) => {
      const db = window.Plexivo.createClient(url, key);
      const got = [];
      const ch = db.channel('changes:notes').onChange((c) => got.push(c)).subscribe();
      await ch.ready();
      const n = await db.from('notes').create({body: 'live in the browser'});
      const start = Date.now();
      while (!got.some((c) => c.record?.id === n.id) && Date.now() - start < 10000) await new Promise((r) => setTimeout(r, 50));
      ch.unsubscribe();
      return {delivered: got.some((c) => c.type === 'insert' && c.record?.id === n.id), state: ch.state};
    }, cfg);
    assert.deepEqual(out, {delivered: true, state: 'closed'});
  });

  await check('browser: broadcast between two tabs', async () => {
    const t2 = await context.newPage();
    await t2.goto(pageUrl);
    await t2.evaluate(async ({url, key}) => {
      const db = window.Plexivo.createClient(url, key);
      window.__got = [];
      window.__ch = db.channel('room:browser').onBroadcast('hello', (p) => window.__got.push(p)).subscribe();
      await window.__ch.ready();
    }, cfg);
    await tab.evaluate(async ({url, key}) => {
      const db = window.Plexivo.createClient(url, key);
      const ch = db.channel('room:browser').subscribe();
      await ch.ready();
      ch.sendBroadcast('hello', {from: 'tab one'});
      await new Promise((r) => setTimeout(r, 300));
      ch.unsubscribe();
    }, cfg);
    await t2.waitForFunction(() => window.__got.length > 0, null, {timeout: 10_000});
    assert.deepEqual(await t2.evaluate(() => window.__got[0]), {from: 'tab one'});
    await t2.close();
  });

  await check('browser: throwOnError false and abortSignal behave in the browser', async () => {
    const out = await tab.evaluate(async ({url, key}) => {
      const db = window.Plexivo.createClient(url, key, {throwOnError: false});
      const missing = await db.from('no_such_table').select('*');
      const c = new AbortController();
      c.abort();
      const aborted = await db.from('notes').abortSignal(c.signal);
      return {missing: missing.error?.code, aborted: aborted.error?.code, trace: Boolean(missing.error?.traceId)};
    }, cfg);
    assert.deepEqual(out, {missing: 'table_not_exposed', aborted: 'aborted', trace: true});
  });

  await check('browser: a page on another origin is refused', async () => {
    const t3 = await context.newPage();
    await t3.goto(`http://127.0.0.1:${otherPort}/`);
    const out = await t3.evaluate(async ({url, key}) => {
      const db = window.Plexivo.createClient(url, key, {persistSession: false});
      try {
        const rows = await db.from('profiles').select('*');
        return {data: rows.length};
      } catch (e) {
        return {code: e.code, status: e.status};
      }
    }, cfg);
    await t3.close();
    assert.equal(out.data, undefined, 'the other origin received data');
    assert.ok(['origin_denied', 'network_error'].includes(out.code), JSON.stringify(out));
  });

  await check('browser: sign-out clears the stored session', async () => {
    const out = await tab.evaluate(async ({url, key}) => {
      const db = window.Plexivo.createClient(url, key);
      await db.auth.signOut();
      return Object.keys(localStorage).filter((k) => k.startsWith('plexivo-client:') && !k.endsWith(':pkce')).length;
    }, cfg);
    assert.equal(out, 0);
    await tab.reload();
    assert.equal(await tab.evaluate(({url, key}) => window.Plexivo.createClient(url, key).auth.getSession(), cfg), null);
  });

  await check('browser: no uncaught errors on the page', async () => {
    assert.deepEqual(consoleErrors, []);
  });
} finally {
  await browser.close();
  http.close();
  otherHttp.close();
}
finish();
