// A small blog and shop, created with the secret key through raw SQL
// (POST /sql/v1), exactly as a developer would. Row-level security is the
// whole security model: the publishable key can do nothing these policies
// do not allow.

export const SCHEMA = [
  `CREATE TYPE post_status AS ENUM ('draft', 'published', 'archived')`,

  // Profiles: one per user, readable by everyone, written only by its owner.
  `CREATE TABLE profiles (
     id uuid PRIMARY KEY DEFAULT auth.uid(),
     username text NOT NULL UNIQUE CHECK (length(username) BETWEEN 2 AND 40),
     country text,
     bio text,
     created_at timestamptz NOT NULL DEFAULT now()
   )`,
  `ALTER TABLE profiles ENABLE ROW LEVEL SECURITY`,
  `CREATE POLICY profiles_read ON profiles FOR SELECT TO anon, authenticated USING (true)`,
  `CREATE POLICY profiles_insert ON profiles FOR INSERT TO authenticated WITH CHECK (id = auth.uid())`,
  `CREATE POLICY profiles_update ON profiles FOR UPDATE TO authenticated USING (id = auth.uid()) WITH CHECK (id = auth.uid())`,

  // Posts: published ones for everyone, drafts only for their author.
  `CREATE TABLE posts (
     id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     author_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles (id),
     editor_id uuid REFERENCES profiles (id),
     title text NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
     body text,
     status post_status NOT NULL DEFAULT 'draft',
     likes integer NOT NULL DEFAULT 0,
     price numeric(14, 4),
     rating double precision,
     labels text[] NOT NULL DEFAULT '{}',
     scores integer[],
     meta jsonb NOT NULL DEFAULT '{}',
     published_on date,
     big bigint,
     created_at timestamptz NOT NULL DEFAULT now(),
     search tsvector GENERATED ALWAYS AS (to_tsvector('english', coalesce(title, '') || ' ' || coalesce(body, ''))) STORED
   )`,
  `CREATE INDEX posts_search_idx ON posts USING gin (search)`,
  `ALTER TABLE posts ENABLE ROW LEVEL SECURITY`,
  `CREATE POLICY posts_read ON posts FOR SELECT TO anon, authenticated USING (status = 'published' OR author_id = auth.uid())`,
  `CREATE POLICY posts_insert ON posts FOR INSERT TO authenticated WITH CHECK (author_id = auth.uid())`,
  `CREATE POLICY posts_update ON posts FOR UPDATE TO authenticated USING (author_id = auth.uid()) WITH CHECK (author_id = auth.uid())`,
  `CREATE POLICY posts_delete ON posts FOR DELETE TO authenticated USING (author_id = auth.uid())`,

  // Comments: visible with their post; written as yourself.
  `CREATE TABLE comments (
     id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     post_id bigint NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
     author_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles (id),
     body text NOT NULL,
     approved boolean NOT NULL DEFAULT false,
     created_at timestamptz NOT NULL DEFAULT now()
   )`,
  `ALTER TABLE comments ENABLE ROW LEVEL SECURITY`,
  `CREATE POLICY comments_read ON comments FOR SELECT TO anon, authenticated USING (EXISTS (SELECT 1 FROM posts p WHERE p.id = post_id))`,
  `CREATE POLICY comments_write ON comments FOR INSERT TO authenticated WITH CHECK (author_id = auth.uid())`,
  `CREATE POLICY comments_own ON comments FOR UPDATE TO authenticated USING (author_id = auth.uid())`,
  `CREATE POLICY comments_delete ON comments FOR DELETE TO authenticated USING (author_id = auth.uid())`,

  // Tags, and posts ⇄ tags.
  `CREATE TABLE tags (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE)`,
  `ALTER TABLE tags ENABLE ROW LEVEL SECURITY`,
  `CREATE POLICY tags_read ON tags FOR SELECT TO anon, authenticated USING (true)`,
  `CREATE POLICY tags_write ON tags FOR INSERT TO authenticated WITH CHECK (true)`,
  `CREATE TABLE post_tags (
     post_id bigint NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
     tag_id bigint NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
     PRIMARY KEY (post_id, tag_id)
   )`,
  `ALTER TABLE post_tags ENABLE ROW LEVEL SECURITY`,
  `CREATE POLICY post_tags_read ON post_tags FOR SELECT TO anon, authenticated USING (EXISTS (SELECT 1 FROM posts p WHERE p.id = post_id))`,
  `CREATE POLICY post_tags_write ON post_tags FOR ALL TO authenticated
     USING (EXISTS (SELECT 1 FROM posts p WHERE p.id = post_id AND p.author_id = auth.uid()))
     WITH CHECK (EXISTS (SELECT 1 FROM posts p WHERE p.id = post_id AND p.author_id = auth.uid()))`,

  // Notes: private to each user (realtime, concurrency, bulk writes).
  `CREATE TABLE notes (
     id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     owner_id uuid NOT NULL DEFAULT auth.uid(),
     body text NOT NULL,
     n integer,
     created_at timestamptz NOT NULL DEFAULT now()
   )`,
  `ALTER TABLE notes ENABLE ROW LEVEL SECURITY`,
  `CREATE POLICY notes_own ON notes FOR ALL TO authenticated USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid())`,

  // Products: a composite key, for upserts.
  `CREATE TABLE products (
     sku text NOT NULL,
     region text NOT NULL,
     name text NOT NULL,
     price numeric(10, 2) NOT NULL CHECK (price >= 0),
     stock integer NOT NULL DEFAULT 0,
     PRIMARY KEY (sku, region)
   )`,
  `ALTER TABLE products ENABLE ROW LEVEL SECURITY`,
  `CREATE POLICY products_all ON products FOR ALL TO authenticated USING (true) WITH CHECK (true)`,

  // A view with joins: the "raw join" path for browsers, under the caller's policies.
  `CREATE VIEW post_feed WITH (security_invoker = true) AS
     SELECT p.id, p.title, p.status, p.likes, p.created_at,
            a.username AS author,
            (SELECT count(*) FROM comments c WHERE c.post_id = p.id) AS comment_count,
            ARRAY(SELECT t.name FROM post_tags pt JOIN tags t ON t.id = pt.tag_id WHERE pt.post_id = p.id ORDER BY t.name) AS tag_names
     FROM posts p JOIN profiles a ON a.id = p.author_id`,

  // Functions: set-returning (a table), RETURNS TABLE, scalar and void.
  `CREATE FUNCTION search_posts(q text) RETURNS SETOF posts LANGUAGE sql STABLE AS
     $$ SELECT * FROM posts WHERE title ILIKE '%' || q || '%' OR body ILIKE '%' || q || '%' $$`,
  `COMMENT ON FUNCTION search_posts(text) IS 'Posts whose title or body mention q. @expose'`,
  `CREATE FUNCTION author_stats(min_likes integer DEFAULT 0) RETURNS TABLE (author text, posts bigint, total_likes bigint) LANGUAGE sql STABLE AS
     $$ SELECT a.username, count(*), sum(p.likes) FROM posts p JOIN profiles a ON a.id = p.author_id WHERE p.likes >= min_likes GROUP BY a.username $$`,
  `COMMENT ON FUNCTION author_stats(integer) IS 'Posts and likes per author. @expose'`,
  `CREATE FUNCTION add_numbers(a integer, b integer) RETURNS integer LANGUAGE sql IMMUTABLE AS $$ SELECT a + b $$`,
  `COMMENT ON FUNCTION add_numbers(integer, integer) IS '@expose'`,
  `CREATE FUNCTION like_post(post_id bigint) RETURNS void LANGUAGE sql AS $$ UPDATE posts SET likes = likes + 1 WHERE id = post_id $$`,
  `COMMENT ON FUNCTION like_post(bigint) IS 'Adds a like, as the caller. @expose'`,
  `CREATE FUNCTION whoami() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT auth.uid() $$`,
  `COMMENT ON FUNCTION whoami() IS '@expose'`,
  `CREATE FUNCTION not_exposed() RETURNS integer LANGUAGE sql AS $$ SELECT 1 $$`,

  // Grants for the request roles, and realtime on the tables that stream.
  `GRANT USAGE ON SCHEMA public TO anon, authenticated`,
  `GRANT SELECT ON profiles, posts, comments, tags, post_tags, post_feed TO anon`,
  `GRANT SELECT, INSERT, UPDATE, DELETE ON profiles, posts, comments, tags, post_tags, notes, products TO authenticated`,
  `GRANT SELECT ON post_feed TO authenticated`,
  `GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO authenticated`,
  `CREATE TRIGGER plexivo_realtime AFTER INSERT OR UPDATE OR DELETE ON notes FOR EACH ROW EXECUTE FUNCTION auth.realtime_notify('id')`,
  `CREATE TRIGGER plexivo_realtime AFTER INSERT OR UPDATE OR DELETE ON posts FOR EACH ROW EXECUTE FUNCTION auth.realtime_notify('id')`,
  `CREATE TRIGGER plexivo_realtime AFTER INSERT OR UPDATE OR DELETE ON comments FOR EACH ROW EXECUTE FUNCTION auth.realtime_notify('id')`
];
